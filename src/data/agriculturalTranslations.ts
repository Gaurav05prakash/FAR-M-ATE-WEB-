/**
 * Translate soil string into current language.
 * Accepts canonical keys, English labels, or any existing soil string.
 */
export function getTranslatedSoil(soil: string | undefined, lang: LanguageCode): string {
  if (!soil || !soil.trim()) return '';
  const trimmed = soil.trim();

  // Look for match in PRESET_SOIL_TYPES
  const matched = PRESET_SOIL_TYPES.find((item) => {
    if (item.key.toLowerCase() === trimmed.toLowerCase()) return true;
    if (item.en.toLowerCase() === trimmed.toLowerCase()) return true;
    // Check if it matches any translation
    return Object.values(item.translations).some(
      (val) => val.toLowerCase() === trimmed.toLowerCase()
    );
  });

  if (matched && matched.translations[lang]) {
    return matched.translations[lang];
  }

  // Partial matches
  if (trimmed.toLowerCase().includes('black') || trimmed.toLowerCase().includes('काली') || trimmed.toLowerCase().includes('నల్ల')) {
    return PRESET_SOIL_TYPES[0].translations[lang] || PRESET_SOIL_TYPES[0].en;
  }
  if (trimmed.toLowerCase().includes('red') || trimmed.toLowerCase().includes('लाल') || trimmed.toLowerCase().includes('ఎర్ర')) {
    return PRESET_SOIL_TYPES[1].translations[lang] || PRESET_SOIL_TYPES[1].en;
  }
  if (trimmed.toLowerCase().includes('alluvial') || trimmed.toLowerCase().includes('जलोढ़') || trimmed.toLowerCase().includes('ఒండ్రు')) {
    return PRESET_SOIL_TYPES[2].translations[lang] || PRESET_SOIL_TYPES[2].en;
  }

  return trimmed;
}

/**
 * Translate crop string into current language.
 * Accepts canonical keys, English labels, or any existing crop string.
 */
export function getTranslatedCrop(crop: string | undefined, lang: LanguageCode): string {
  if (!crop || !crop.trim()) return '';
  const trimmed = crop.trim();

  const matched = PRESET_CROPS.find((item) => {
    if (item.key.toLowerCase() === trimmed.toLowerCase()) return true;
    if (item.en.toLowerCase() === trimmed.toLowerCase()) return true;
    return Object.values(item.translations).some(
      (val) => val.toLowerCase() === trimmed.toLowerCase()
    );
  });

  if (matched && matched.translations[lang]) {
    return matched.translations[lang];
  }

  return trimmed;
}

